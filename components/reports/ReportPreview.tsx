import { Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';

import { COLORS, RADIUS, SHADOWS, SPACING, TYPOGRAPHY } from '@/constants/theme';
import type { ReportLink, ReportSection, ReportViewModel } from '@/types/report';
import { formatLocalDateTime } from '@/utils/dateTime';

function RecordCount({ report }: { report: ReportViewModel }) {
  if (report.totalCount === undefined) return null;
  const total = report.totalCount.toLocaleString();
  const shown = report.exportedCount ?? 0;
  const label = report.countLabel ?? 'records';
  if (report.layoutKind === 'municipal_summary') {
    return <View style={styles.countNotice}><Text style={styles.countText}>This preview summarizes all {total} matching {label}. Use Current Sanitation Register for household-level detail.</Text></View>;
  }
  if (report.previewPage !== undefined && report.previewPageSize && shown > 0) {
    const first = report.previewPage * report.previewPageSize + 1;
    const last = first + shown - 1;
    return <View style={styles.countNotice}><Text style={styles.countText}>{total} {label} match. Preview showing {first.toLocaleString()}–{last.toLocaleString()}. The PDF export includes all matching records with full inspection details.</Text></View>;
  }
  return <View style={styles.countNotice}><Text style={styles.countText}>{total} {label} match the active filters.</Text></View>;
}

function HorizontalTable({ section, onOpen }: { section: ReportSection; onOpen?: (link: ReportLink) => void }) {
  return <ScrollView horizontal showsHorizontalScrollIndicator><View>
    <View style={styles.tableHeader}>{section.columns.map((column) => <Text key={column} style={[styles.cell, styles.headerCell]}>{column}</Text>)}</View>
    {section.rows.length ? section.rows.map((row, rowIndex) => {
      const link = section.rowLinks?.[rowIndex] ?? null;
      return <Pressable key={rowIndex} disabled={!link || !onOpen} onPress={() => link && onOpen?.(link)} style={[styles.tableRow, rowIndex % 2 === 1 && styles.altRow, link && onOpen && styles.linkedRow]}>
        {row.map((cell, index) => <Text key={`${index}-${cell}`} style={styles.cell}>{cell || '—'}</Text>)}
      </Pressable>;
    }) : <Text style={styles.empty}>{section.emptyMessage ?? 'No records matched the selected filters.'}</Text>}
  </View></ScrollView>;
}

export default function ReportPreview({ report, onOpen }: { report: ReportViewModel; onOpen?: (link: ReportLink) => void }) {
  return <View style={styles.paper}>
    <View style={styles.header}><Text style={styles.brand}>SUTA</Text><Text style={styles.jurisdiction}>{report.jurisdiction}</Text><Text style={styles.office}>{report.officeLabel}</Text><Text style={styles.title}>{report.title}</Text></View>
    <View style={styles.meta}><Text style={styles.metaText}><Text style={styles.bold}>Reporting Period: </Text>{report.reportingPeriod}</Text><Text style={styles.metaText}><Text style={styles.bold}>Generated: </Text>{formatLocalDateTime(report.generatedAt)}</Text>{report.scope.map((item) => <Text key={item} style={styles.metaText}>{item}</Text>)}</View>
    <RecordCount report={report} />
    <View style={styles.metrics}>{report.metrics.map((item) => <View key={item.label} style={styles.metric}><Text style={styles.metricValue}>{item.value}</Text><Text style={styles.metricLabel}>{item.label}</Text></View>)}</View>
    {report.highlights.length ? <View style={styles.highlights}>{report.highlights.map((item) => <Text key={item} style={styles.highlight}>• {item}</Text>)}</View> : null}
    {report.sections.map((section) => <View key={section.title} style={styles.section}><Text style={styles.heading}>{section.title}</Text><HorizontalTable section={section} onOpen={onOpen} /></View>)}
    {report.layoutKind !== 'municipal_summary' ? <View style={styles.detailNotice}><Text style={styles.bold}>PDF wide register</Text><Text style={styles.metaText}>Each included place or inspection is one row containing every checklist field, testing data, findings, remarks, result/risk, and reinspection information. Only photos use an optional appendix.</Text></View> : null}
    {report.generatedBy === 'bsi' ? <View style={styles.signature}><Text style={styles.heading}>Submission signatures</Text><Text style={styles.metaText}>The exported PDF includes Prepared by and Received / Reviewed by signature areas.</Text></View> : null}
    <View style={styles.footer}><Text style={styles.footerText}>Generated by SUTA · Report preview</Text></View>
  </View>;
}

